const makeTemplate = (
  overrides: Record<number, [number, number]> = {}
): LandmarkLike[] => {
  // Base standing neutral pose in normalized 0-1 canvas coordinates
  const baseLandmarks: Record<number, [number, number]> = {
    0: [0.5, 0.12], // nose
    1: [0.49, 0.11],
    2: [0.48, 0.11],
    3: [0.47, 0.11],
    4: [0.51, 0.11],
    5: [0.52, 0.11],
    6: [0.53, 0.11],
    7: [0.45, 0.13], // left ear
    8: [0.55, 0.13], // right ear
    9: [0.48, 0.15],
    10: [0.52, 0.15],
    11: [0.43, 0.23], // left shoulder
    12: [0.57, 0.23], // right shoulder
    13: [0.4, 0.38], // left elbow
    14: [0.6, 0.38], // right elbow
    15: [0.38, 0.52], // left wrist
    16: [0.62, 0.52], // right wrist
    17: [0.37, 0.55],
    18: [0.63, 0.55],
    19: [0.38, 0.56],
    20: [0.62, 0.56],
    21: [0.39, 0.54],
    22: [0.61, 0.54],
    23: [0.46, 0.52], // left hip
    24: [0.54, 0.52], // right hip
    25: [0.45, 0.72], // left knee
    26: [0.55, 0.72], // right knee
    27: [0.44, 0.9], // left ankle
    28: [0.56, 0.9], // right ankle
    29: [0.44, 0.93],
    30: [0.56, 0.93],
    31: [0.42, 0.95],
    32: [0.58, 0.95],
  };

  const points: LandmarkLike[] = [];
  for (let i = 0; i < 33; i++) {
    const coords = overrides[i] ?? baseLandmarks[i] ?? [0.5, 0.5];
    points.push({
      x: coords[0],
      y: coords[1],
      z: 0,
      visibility: 0.95,
    });
  }
  return points;
};

